# Icons per semester (1-8)
SEMESTER_ICONS = {
    1: '📘', 2: '📗', 3: '📙', 4: '📕',
    5: '🧠', 6: '⚙️', 7: '🎯', 8: '🎓',
}


def year_from_semester(s):
    return (s + 1) // 2


class Command(BaseCommand):
    help = 'Seed the database with FINKI subjects (180+ predmeti).'

    def add_arguments(self, parser):
        parser.add_argument(
            '--reset',
            action='store_true',
            help='Delete all existing subjects before seeding.',
        )

    def handle(self, *args, **opts):
        if opts['reset']:
            count = Subject.objects.count()
            Subject.objects.all().delete()
            self.stdout.write(self.style.WARNING(f"Избришани {count} стари предмети."))

        added = 0
        updated = 0
        for code, name, semester, stype, group, prereq in SUBJECTS:
            year = year_from_semester(semester)
            slug = _slug(code, name)

            obj, created = Subject.objects.update_or_create(
                code=code,
                defaults={
                    'name': name,
                    'slug': slug,
                    'semester': semester,
                    'year': year,
                    'subject_type': stype,
                    'elective_group': group,
                    'prerequisites': prereq,
                    'icon': SEMESTER_ICONS.get(semester, '📘'),
                    'level': 'bachelor',
                },
            )
            if created:
                added += 1
            else:
                updated += 1

        # === EXTRA subjects — skip duplicates by normalized name ===
        def normalize(s):
            return s.lower().replace(' ', '').replace('-', '').strip()

        existing_names = {normalize(n) for n in Subject.objects.values_list('name', flat=True)}

        extra_added = 0
        extra_skipped = 0
        for code, name, semester, stype, group, prereq in EXTRA_SUBJECTS:
            if normalize(name) in existing_names:
                extra_skipped += 1
                continue
            year = year_from_semester(semester)
            slug = _slug(code, name)
            Subject.objects.update_or_create(
                code=code,
                defaults={
                    'name': name,
                    'slug': slug,
                    'semester': semester,
                    'year': year,
                    'subject_type': stype,
                    'elective_group': group,
                    'prerequisites': prereq,
                    'icon': SEMESTER_ICONS.get(semester, '📘'),
                    'level': 'bachelor',
                },
            )
            existing_names.add(normalize(name))
            extra_added += 1

        self.stdout.write(self.style.SUCCESS(
            f"\n✓ Готово.\n"
            f"  Главна листа: {added} додадени, {updated} ажурирани.\n"
            f"  Дополнителни: {extra_added} додадени, {extra_skipped} прескокнати (дупликати).\n"
            f"  Вкупно во базата: {Subject.objects.count()}."
        ))
